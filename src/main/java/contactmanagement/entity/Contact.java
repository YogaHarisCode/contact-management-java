package contactmanagement.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * JPA entity representing a contact that belongs to one {@link User}, stored in the
 * {@code contacts} table.
 *
 * <p>The {@code id} is a UUID generated by Hibernate when the entity is persisted, so it is
 * {@code null} on a new instance until {@code save()} has been called. Getters and setters are
 * generated by Lombok.
 */
@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "contacts")
public class Contact {

    /** Unique identifier (UUID string), generated by Hibernate. Maximum 100 characters. */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "id", nullable = false, length = 100)
    private String id;

    /** First name of the contact. Required, maximum 100 characters. */
    @Column(name = "first_name", nullable = false, length = 100)
    private String firstName;

    /** Last name of the contact. Optional, maximum 100 characters. */
    @Column(name = "last_name", length = 100)
    private String lastName;

    /** Email address of the contact. Optional, maximum 200 characters in the entity mapping. */
    @Column(name = "email", length = 200)
    private String email;

    /** Phone number of the contact. Optional, maximum 20 characters. */
    @Column(name = "phone", length = 20)
    private String phone;

    /**
     * Owner of this contact, stored in the {@code username} foreign key column.
     *
     * <p>Loaded lazily, so the {@link User} row is only fetched when this field is accessed.
     * A contact cannot exist without an owner.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "username", nullable = false)
    private User user;
}