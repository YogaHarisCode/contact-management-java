package contactmanagement.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.springframework.data.domain.Persistable;

/**
 * JPA entity representing an application user, stored in the {@code users} table.
 *
 * <p>The {@code username} is the natural primary key. Because the key is assigned by the
 * application instead of being generated by the database, this class implements
 * {@link Persistable} so Spring Data can tell whether an instance is new. Without it,
 * {@code save()} would call {@code merge()} and silently overwrite an existing row when two
 * registrations with the same username race each other.
 *
 * <p>Getters and setters are generated by Lombok. The {@code password} field always holds a
 * BCrypt hash, never the plain-text password.
 */
@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "users")
public class User implements Persistable<String> {

    /** Unique login name and primary key. Maximum 100 characters. */
    @Id
    @Column(name = "username", length = 100, nullable = false)
    private String username;

    /** BCrypt hash of the user's password. Must never be exposed in any response or log. */
    @Column(name = "password", length = 100, nullable = false)
    private String password;

    /** Display name of the user. Maximum 100 characters. */
    @Column(name = "name", length = 100, nullable = false)
    private String name;

    /** Authentication token issued at login and checked on every authenticated request; {@code null} until the first login. */
    @Column(name = "token", length = 100, unique = true)
    private String token;

    /**
     * Expiration time of {@link #token} as epoch milliseconds (UTC), or {@code null} when no
     * token has been issued.
     */
    @Column(name = "token_expired_at")
    private Long tokenExpiredAt;

    /**
     * Transient flag telling Spring Data whether this instance still has to be inserted
     * ({@code persist}) or already exists ({@code merge}). It is not mapped to a column.
     */
    @Transient
    @Getter(AccessLevel.NONE)
    @Setter(AccessLevel.NONE)
    private boolean newEntity = true;

    /**
     * Returns the entity identifier required by {@link Persistable}.
     *
     * @return the username, which is the primary key
     */
    @Override
    public String getId() {
        return username;
    }

    /**
     * Tells Spring Data whether this entity has not been persisted yet.
     *
     * @return {@code true} for a freshly created instance, {@code false} once it has been
     *         saved or loaded from the database
     */
    @Override
    public boolean isNew() {
        return newEntity;
    }

    /**
     * JPA lifecycle callback that marks the instance as existing after it is loaded from or
     * written to the database.
     */
    @PostLoad
    @PostPersist
    void markNotNew() {
        this.newEntity = false;
    }
}